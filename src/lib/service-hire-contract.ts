const DAY_MS = 86_400_000;
const utc = (iso: string) => {
  const [y, m, d] = iso.split("-").map(Number);
  return Date.UTC(y, m - 1, d);
};
const daysIn = (y: number, m: number) => new Date(Date.UTC(y, m, 0)).getUTCDate(); // m: 1-12

/** ระยะเวลาจ้างเป็น ปี/เดือน/วัน (นับรวมวันสิ้นสุด) เช่น 1 ต.ค. – 30 ก.ย. = 0 ปี 12 เดือน 0 วัน */
export function durationYmd(start: string | null, end: string | null): { y: number; m: number; d: number } | null {
  if (!start || !end || end < start) return null;
  const a = new Date(utc(start));
  const b = new Date(utc(end) + DAY_MS); // วันสิ้นสุดแบบไม่รวม
  let months = (b.getUTCFullYear() - a.getUTCFullYear()) * 12 + (b.getUTCMonth() - a.getUTCMonth());
  let days = b.getUTCDate() - a.getUTCDate();
  if (days < 0) {
    months -= 1;
    const pm = b.getUTCMonth() === 0 ? 12 : b.getUTCMonth();
    const py = b.getUTCMonth() === 0 ? b.getUTCFullYear() - 1 : b.getUTCFullYear();
    days += daysIn(py, pm);
  }
  return { y: Math.floor(months / 12), m: months % 12, d: days };
}

/** จำนวนงวด (เดือนปฏิทินที่คาบเกี่ยว) และค่าจ้างรวม: เดือนเต็ม = เดือนละเต็ม, เดือนแรก/สุดท้ายไม่เต็ม = วันละ (เดือนละ ÷ 30) × จำนวนวัน */
export function installmentsAndTotal(start: string | null, end: string | null, monthly: number | null): { installments: number; total: number } | null {
  if (!start || !end || end < start || !monthly) return null;
  let [y, m] = start.split("-").map(Number);
  const [ey, em] = end.split("-").map(Number);
  let installments = 0;
  let total = 0;
  for (;;) {
    const first = Date.UTC(y, m - 1, 1);
    const last = Date.UTC(y, m - 1, daysIn(y, m));
    const from = Math.max(first, utc(start));
    const to = Math.min(last, utc(end));
    const worked = Math.round((to - from) / DAY_MS) + 1;
    total += worked >= daysIn(y, m) ? monthly : Math.min(monthly, (monthly / 30) * worked);
    installments += 1;
    if (y === ey && m === em) break;
    m += 1;
    if (m > 12) {
      m = 1;
      y += 1;
    }
  }
  return { installments, total: Math.round(total * 100) / 100 };
}

