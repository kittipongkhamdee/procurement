// งบดำเนินงาน 4 ลักษณะ (ค่าตอบแทน ใช้สอย วัสดุ สาธารณูปโภค) + งบลงทุน ค่าครุภัณฑ์ + อื่นๆ (ระบุ) — ผู้ใช้กำหนด ต.ค. 2569
// ค่าจ้างครูอัตราจ้างแบบจ้างเหมาบริการ (ผ่านสัญญาจ้าง/ใบส่งมอบงาน) = ค่าใช้สอย

export const EXPENSE_CATEGORIES = [
  { label: "ค่าตอบแทน", short: "ค่าตอบแทน", hint: "ค่าวิทยากร ค่าสอนพิเศษรายครั้ง ค่าตอบแทนนอกเวลา" },
  { label: "ค่าใช้สอย", short: "ค่าใช้สอย", hint: "ค่าอาหาร/อาหารว่าง จ้างเหมาบริการ (เช่น ค่าจ้างครูอัตราจ้าง) ค่าเช่า ค่าเดินทางไปราชการ (เบี้ยเลี้ยง ที่พัก พาหนะ)" },
  { label: "ค่าวัสดุ", short: "ค่าวัสดุ", hint: "วัสดุสำนักงาน วัสดุการศึกษา วัสดุคอมพิวเตอร์ — สิ้นเปลือง/อายุใช้งานไม่ยืนนาน" },
  { label: "ค่าสาธารณูปโภค", short: "สาธารณูปโภค", hint: "ค่าไฟฟ้า ค่าน้ำประปา ค่าโทรศัพท์ อินเทอร์เน็ต" },
  { label: "ค่าครุภัณฑ์", short: "ค่าครุภัณฑ์", hint: "สิ่งของคงทนถาวร อายุใช้งานยืนนาน (งบลงทุน)" },
  { label: "อื่นๆ (ระบุ)", short: "อื่นๆ", hint: "เช่น ค่าที่ดินและสิ่งก่อสร้าง หรือรายจ่ายที่ไม่เข้าหมวดข้างต้น" },
] as const;

export const EXPENSE_LABELS: string[] = EXPENSE_CATEGORIES.map((c) => c.label);
export const OTHER_EXPENSE_INDEX = EXPENSE_CATEGORIES.length - 1;
export const SERVICE_EXPENSE_INDEX = 1; // ค่าใช้สอย

/** หมวดเดิม (5 แถว ก่อน ต.ค. 2569) → หมวดใหม่ — "จัดซื้อจัดจ้าง" เดิมรวมทั้งซื้อของและจ้าง นับเป็นค่าวัสดุ;
 *  "ค่าเบี้ยเลี้ยง/ค่าตอบแทน" แยกย้อนหลังไม่ได้ นับเป็นค่าตอบแทน */
const LEGACY: [string, number][] = [
  ["ค่าเบี้ยเลี้ยง/ค่าตอบแทน", 0],
  ["ค่าเดินทางไปราชการ", 1],
  ["จัดซื้อจัดจ้าง", 2],
];

/** หมวด (index) ของรายการที่บันทึกไว้ — ชื่อหมวดอาจต่อท้ายรายละเอียด เช่น "ค่าใช้สอย ค่าจ้าง… ประจำเดือน…" (-1 = ไม่รู้จัก) */
export function expenseCategoryIndex(label: string | null | undefined): number {
  const l = (label ?? "").trim();
  if (!l) return -1;
  if (/^อื่นๆ/.test(l)) return OTHER_EXPENSE_INDEX;
  const i = EXPENSE_LABELS.findIndex((c) => l.startsWith(c));
  if (i >= 0) return i;
  return LEGACY.find(([old]) => l.startsWith(old))?.[1] ?? -1;
}

/** บันทึกที่ใช้หมวดเดิม 5 แถว — PDF พิมพ์ตามที่บันทึกไว้ (ไม่เปลี่ยนหน้าตาเอกสารเก่า) */
export function isLegacySummary(items: { label: string }[]): boolean {
  return items.some((it) => LEGACY.some(([old]) => it.label.trim().startsWith(old)));
}
